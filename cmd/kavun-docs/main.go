// Command kavun-docs renders the Markdown language reference from kavun_reference.json files (written by
// cmd/kavun-gen; see package reference). It reads references only, never Go source, so it works the same on Kavun's
// own reference and on an embedder's.
//
//	kavun-docs [-check] -out <docs root>/reference [-with <kavun_reference.json>[=<docs URL>]]… <kavun_reference.json>…
//
// The references given as arguments are rendered: several make one merged site. A -with reference (repeatable) is
// loaded only to resolve links into its origin, whose pages live at the docs URL after "=" (by default the file's
// docs field); the path ends at the first "=", so a -with path cannot contain one. A type, module or builtin function declared by two loaded references, or an origin given twice, is
// refused. A link into a -with origin whose docs URL is unknown, and a kavun:doc/ link to a page (or heading) the docs
// root — the output directory's parent — does not hold, are refused. The text kavun-docs writes itself (a world
// module's grant line, the member-function matrix's introduction) links to Kavun's guide pages: relative when
// Kavun's own reference is rendered, else under Kavun's docs URL — so an embedder's run gives Kavun's
// kavun_reference.json with -with (its docs field, or the URL after "=").
//
// The output directory is wholly generated: a file there that no page produces is deleted. Every file there must
// carry a generated header (`<!-- Code generated by <tool> … DO NOT EDIT. -->`); a file that does not — a
// hand-written guide, an image — makes the command fail, naming it, before anything is written or deleted (with
// -check too). With -check nothing is written: every file that differs from the one on disk (or is stale) is
// reported as a diff, and the command exits 1. The page layout is described in internal/kavundocs.
package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/jokruger/kavun/internal/kavundocs"
)

// withFlag collects the repeated -with values.
type withFlag []kavundocs.With

func (w *withFlag) String() string {
	parts := make([]string, len(*w))
	for i, v := range *w {
		parts[i] = v.Path
		if v.URL != "" {
			parts[i] += "=" + v.URL
		}
	}
	return strings.Join(parts, " ")
}

func (w *withFlag) Set(s string) error {
	v, err := kavundocs.ParseWith(s)
	if err != nil {
		return err
	}
	*w = append(*w, v)
	return nil
}

func main() {
	check := flag.Bool("check", false, "compare the generated pages with those on disk instead of writing them")
	out := flag.String("out", "", "the output `directory` (<docs root>/reference), wholly generated: files no page produces are deleted, and a file without a generated header is refused")
	var with withFlag
	flag.Var(&with, "with", "a `reference[=URL]` loaded for links only (repeatable): a kavun_reference.json, then the URL of its origin's docs root (default: the file's docs field); the path cannot contain \"=\"")
	flag.Usage = func() {
		fmt.Fprintln(os.Stderr, "usage: kavun-docs [-check] -out <dir> [-with <kavun_reference.json>[=<docs URL>]]… <kavun_reference.json>…")
		flag.PrintDefaults()
	}
	flag.Parse()
	if flag.NArg() == 0 || *out == "" {
		flag.Usage()
		os.Exit(2)
	}
	err := kavundocs.Run(kavundocs.Config{Out: *out, Check: *check, Render: flag.Args(), With: with, Stdout: os.Stdout})
	if err != nil {
		fmt.Fprintln(os.Stderr, "kavun-docs:", err)
		os.Exit(1)
	}
}
