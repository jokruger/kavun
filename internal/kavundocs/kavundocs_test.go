// TestRun: the output root is wholly generated — -check reports a missing, a changed and a stale page and fails,
// a run writes the pages and deletes the stale one, and -check is clean afterwards.
func TestRun(t *testing.T) {
	out := filepath.Join(t.TempDir(), "reference")
	stale := filepath.Join(out, "types", "gone.md")
	if err := os.MkdirAll(filepath.Dir(stale), 0o755); err != nil {
		t.Fatal(err)
	}
	const header = "<!-- Code generated by kavun-gen from gone.go; DO NOT EDIT. -->\n"
	if err := os.WriteFile(stale, []byte(header+"old\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(out, "types", "gadget.md"), []byte(header+"edited\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	cfg := Config{Out: out, Check: true, Render: []string{fixtureRefPath("ext")}, With: []With{kavunStub(t)}}
	var stdout bytes.Buffer
	cfg.Stdout = &stdout
	err := Run(cfg)
	got := stdout.String()
	if err == nil || !strings.Contains(err.Error(), "3 generated file(s) out of date") ||
		!strings.Contains(got, "gone.md (on disk)") || !strings.Contains(got, "-old") || !strings.Contains(got, "-edited") || !strings.Contains(got, "function_matrix.md (generated)") {
		t.Fatalf("-check: %v\n%s", err, got)
	}

	cfg.Check = false
	if err := Run(cfg); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("the stale page still exists")
	}
	cfg.Check = true
	stdout.Reset()
	if err := Run(cfg); err != nil || stdout.Len() != 0 {
		t.Fatalf("-check after a run: %v\n%s", err, stdout.String())
	}
	want, err := os.ReadFile(filepath.Join("testdata", "ext", "types", "gadget.md.golden"))
	if err != nil {
		t.Fatal(err)
	}
	if page, err := os.ReadFile(filepath.Join(out, "types", "gadget.md")); err != nil || !bytes.Equal(page, want) {
		t.Fatalf("the written page is not the golden: %v\n%s", err, page)
	}

	if err := Run(Config{Out: out}); err == nil || !strings.Contains(err.Error(), "no reference to render") {
		t.Fatalf("no reference: %v", err)
	}
	if err := Run(Config{Render: []string{fixtureRefPath("ext")}}); err == nil || !strings.Contains(err.Error(), "no output root") {
		t.Fatalf("no -out: %v", err)
	}
}

// TestWith: a -with reference is loaded for links only — merged with the rendered ones (a conflict refused), its
// pages not rendered, its docs URL the -with value or else the file's docs field.
func TestWith(t *testing.T) {
	for _, c := range []struct {
		in   string
		want With
	}{
		{"kavun_reference.json", With{Path: "kavun_reference.json"}},
		{"a/ref.json=https://example.com/docs", With{Path: "a/ref.json", URL: "https://example.com/docs"}},
		{"ref.json=https://example.com/?a=b", With{Path: "ref.json", URL: "https://example.com/?a=b"}},
	} {
		if got, err := ParseWith(c.in); err != nil || got != c.want {
			t.Errorf("ParseWith(%q) = %+v, %v", c.in, got, err)
		}
	}
	if _, err := ParseWith("=https://example.com"); err == nil {
		t.Error("ParseWith accepted a value with no path")
	}

	dir := t.TempDir()
	write := func(name string, ref *reference.Reference) string {
		t.Helper()
		var buf bytes.Buffer
		if err := ref.Write(&buf); err != nil {
			t.Fatal(err)
		}
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, buf.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
		return p
	}
	core := fixtureRef(t, "core")
	core.Origin, core.Docs = "example.com/core", "https://example.com/core/docs/"
	corePath := write("core.json", core)
	ext := fixtureRef(t, "module")
	ext.Origin = "example.com/ext"
	extPath := write("ext.json", ext)

	stub := kavunStub(t)
	site, err := Load([]string{extPath}, []With{{Path: corePath}, stub})
	if err != nil {
		t.Fatal(err)
	}
	if _, ok := site.Rendered.Type("widget"); ok {
		t.Error("a -with reference is rendered")
	}
	if _, ok := site.Links.Type("widget"); !ok {
		t.Error("a -with reference is not in the link set")
	}
	if got := site.URLs["example.com/core"]; got != "https://example.com/core/docs" {
		t.Errorf("the default docs URL: %q", got)
	}
	site, err = Load([]string{extPath}, []With{{Path: corePath, URL: "https://mirror.example.com/docs"}, stub})
	if err != nil || site.URLs["example.com/core"] != "https://mirror.example.com/docs" {
		t.Errorf("the given docs URL: %v %+v", err, site)
	}
	pages, err := site.Pages("reference")
	if err != nil || pages["types/widget.md"] != nil || pages["modules/path.md"] == nil {
		t.Errorf("only the positional reference is rendered: %v", err)
	}

	// the same type in a -with reference and a rendered one
	clash := fixtureRef(t, "ext") // declares gadget, as core does
	clash.Origin = "example.com/clash"
	if _, err := Load([]string{write("clash.json", clash)}, []With{{Path: corePath}}); err == nil || !strings.Contains(err.Error(), "type gadget is declared by") {
		t.Errorf("expected a merge conflict, got %v", err)
	}
	// the same origin twice
	if _, err := Load([]string{corePath}, []With{{Path: corePath}}); err == nil || !strings.Contains(err.Error(), "origin example.com/core is given twice") {
		t.Errorf("expected a repeated origin, got %v", err)
	}
}

// TestRunRefusesForeignFiles: a hand-written page and an image under -out make the run fail, naming both, with and
// without -check — and nothing there is written or deleted, not even the generated stale page beside them.
func TestRunRefusesForeignFiles(t *testing.T) {
	out := t.TempDir()
	before := map[string]string{
		"guide.md":       "# A guide\n\nWritten by hand.\n",
		"pic.png":        "\x89PNG\r\n\x1a\n",
		"types/stale.md": "<!-- Code generated by kavun-docs from x.go; DO NOT EDIT. -->\nstale\n",
	}
	for rel, content := range before {
		p := filepath.Join(out, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for _, check := range []bool{true, false} {
		var stdout bytes.Buffer
		err := Run(Config{Out: out, Check: check, Render: []string{fixtureRefPath("ext")}, With: []With{kavunStub(t)}, Stdout: &stdout})
		if err == nil || !strings.Contains(err.Error(), "guide.md") || !strings.Contains(err.Error(), "pic.png") || strings.Contains(err.Error(), "stale.md") {
			t.Fatalf("check %v: expected a refusal naming guide.md and pic.png, got %v", check, err)
		}
		if stdout.Len() != 0 {
			t.Fatalf("check %v: a refused run printed diffs:\n%s", check, stdout.String())
		}
	}
	n := 0
	_ = filepath.WalkDir(out, func(p string, e os.DirEntry, err error) error {
		if err != nil || e.IsDir() {
			return err
		}
		n++
		rel, _ := filepath.Rel(out, p)
		if got, err := os.ReadFile(p); err != nil || string(got) != before[filepath.ToSlash(rel)] {
			t.Errorf("%s was touched", rel)
		}
		return nil
	})
	if n != len(before) {
		t.Fatalf("expected the %d files untouched, found %d", len(before), n)
	}
}

// TestLinks: every kavun: link renders as a path relative to its page — the same page as a bare fragment, another
// page of the site, a module, the builtins, a guide page beside the reference — or, into a -with origin, as a URL
// under its docs URL; a guide page or heading that does not exist, and a -with origin without a docs URL, are
// refused with the position of the declaration holding the link.
func TestLinks(t *testing.T) {
	text := func(md string) reference.Doc {
		return reference.Doc{{Kind: reference.BlockText, Markdown: md}}
	}
	fn := func(name, summary string, doc reference.Doc) reference.Callable {
		return reference.Callable{Name: name, Pure: true, Signature: reference.Signature{Template: "()"}, Result: "int",
			Summary: summary, Doc: doc, Pos: reference.Pos{File: "x/" + name + ".go", Line: 3}}
	}
	site := func(t *testing.T, root reference.Doc, withURL string) *Site {
		t.Helper()
		ref := &reference.Reference{Schema: 1, Origin: "example.com/site",
			Types: []reference.Type{
				{Name: "widget", Summary: "A widget; see [gadget](kavun:type/gadget).", Doc: root, Pos: reference.Pos{File: "x/widget.go", Line: 1},
					Members: []reference.Callable{
						fn("size", "The size; see [`double`](kavun:type/widget/double).", text("Also [the notes](kavun:type/widget#notes), [`tick`](kavun:type/gadget/tick), "+
							"[the gadget's notes](kavun:type/gadget#gadget-notes), [`run`](kavun:module/m/run), [`len`](kavun:builtin/len), "+
							"[builtins](kavun:builtins#intro), [the guide](kavun:doc/guide#errors), [nested](kavun:doc/sub/page), "+
							"[web](https://example.com/x), `[code](kavun:type/nope)`.")),
						fn("double", "Twice.", reference.Doc{}),
					}},
				{Name: "gadget", Summary: "A gadget.", Doc: text("## Gadget notes"), Members: []reference.Callable{fn("tick", "Tick.", reference.Doc{})}},
			},
			Builtins: &reference.Builtins{Doc: text("## Intro\nSee [the widget](kavun:type/widget) and [the guide](kavun:doc/guide)."),
				Functions: []reference.Callable{fn("len", "Length; see [`size`](kavun:type/widget/size).", reference.Doc{})}},
			Modules: []reference.Module{{Name: "m", Summary: "A module; see [`len`](kavun:builtin/len).", Doc: text("Uses [`size`](kavun:type/widget/size)."),
				Functions: []reference.Callable{fn("run", "Run; see [the other](kavun:type/other.thing/go).", reference.Doc{})}}},
		}
		other := &reference.Reference{Schema: 1, Origin: "example.com/other", Docs: "https://other.example.com/docs",
			Types: []reference.Type{{Name: "other.thing", Module: "other", Summary: "A thing.", Members: []reference.Callable{fn("go", "Go.", reference.Doc{})}}}}
		s, err := NewSite([]*reference.Reference{ref}, []*reference.Reference{ref, other}, map[string]string{"example.com/other": withURL, reference.KavunOrigin: kavunDocs})
		if err != nil {
			t.Fatal(err)
		}
		return s
	}
	docs := t.TempDir()
	for rel, content := range map[string]string{
		"guide.md":    "# Guide\n\n## Errors\n\n## Errors\n\n<a id=\"anchored\"></a>\n```md\n## Fenced\n```\n",
		"sub/page.md": "# Page\n",
	} {
		p := filepath.Join(docs, filepath.FromSlash(rel))
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	out := filepath.Join(docs, "reference")

	pages, err := site(t, text("## Notes"), "https://other.example.com/docs").Pages(out)
	if err != nil {
		t.Fatal(err)
	}
	for page, wants := range map[string][]string{
		"types/widget.md": {
			"A widget; see [gadget](gadget.md).",
			"The size; see [`double`](#double).",
			"Also [the notes](#notes), [`tick`](gadget.md#tick), [the gadget's notes](gadget.md#gadget-notes), [`run`](../modules/m.md#run), " +
				"[`len`](../builtins.md#len), [builtins](../builtins.md#intro), [the guide](../../guide.md#errors), [nested](../../sub/page.md), " +
				"[web](https://example.com/x), `[code](kavun:type/nope)`.",
		},
		"builtins.md":     {"See [the widget](types/widget.md) and [the guide](../guide.md).", "Length; see [`size`](types/widget.md#size)."},
		"modules/m.md":    {"A module; see [`len`](../builtins.md#len).", "Uses [`size`](../types/widget.md#size).", "Run; see [the other](https://other.example.com/docs/reference/types/other_thing.md#go)."},
		"modules.md":      {"| A module; see [`len`](builtins.md#len). |"},
		MatrixPage:        {"[gadget](types/gadget.md) | [widget](types/widget.md)"},
		"types/gadget.md": {"# gadget"},
	} {
		for _, want := range wants {
			if !strings.Contains(string(pages[page]), want) {
				t.Errorf("%s lacks %q:\n%s", page, want, pages[page])
			}
		}
	}

	// a repeated heading is numbered, an explicit anchor counts, a heading in a fenced block does not
	for frag, ok := range map[string]bool{"errors-1": true, "anchored": true, "fenced": false, "errors-2": false} {
		_, err := site(t, text("## Notes\n[g](kavun:doc/guide#"+frag+")"), "https://x").Pages(out)
		if (err == nil) != ok {
			t.Errorf("#%s: %v", frag, err)
		}
	}
	for _, c := range []struct {
		root    string
		withURL string
		want    string
	}{
		{"[g](kavun:doc/nope) [again](kavun:doc/nope)", "https://x", "x/widget.go:1: kavun:doc/nope: no guide page nope.md in " + docs},
		{"[g](kavun:doc/guide#nope)", "https://x", `x/widget.go:1: kavun:doc/guide#nope: guide.md has no heading or anchor "nope"`},
		{"## Notes", "", "x/run.go:3: kavun:type/other.thing/go: example.com/other is not rendered and has no docs URL"},
		{"[t](kavun:type/nope)", "https://x", "x/widget.go:1: kavun:type/nope: no type nope"},
	} {
		_, err := site(t, text(c.root), c.withURL).Pages(out)
		if err == nil || strings.Count(err.Error(), c.want) != 1 {
			t.Errorf("%s: got %v, want %q once", c.root, err, c.want)
		}
	}
}

// TestKavunGuideLinks: kavun-docs' own text (a world module's grant line, the matrix introduction) links to Kavun's
// guide pages — relative and checked when Kavun's reference is rendered, under Kavun's docs URL when it is a -with
// reference, refused when it is neither rendered nor given a docs URL.
func TestKavunGuideLinks(t *testing.T) {
	ref := fixtureRef(t, "module_plain")   // os: a world module, so its page carries the grant line
	ref.Types = fixtureRef(t, "ext").Types // a type with members, so there is a matrix
	grant := "[embedding.md § The module grant]"
	matrix := "[member functions are values]"

	// rendered: Kavun's own pages, relative to the guide pages beside the output root
	kavun := *ref
	kavun.Origin = reference.KavunOrigin
	docs := t.TempDir()
	write := func(rel, content string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(docs, rel), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	write("embedding.md", "# Embedding\n\n### The module grant\n")
	write("types.md", "# Types\n\n## Member functions are values\n")
	pages, err := siteOf(t, &kavun).Pages(filepath.Join(docs, "reference"))
	if err != nil {
		t.Fatal(err)
	}
	if got := string(pages["modules/os.md"]); !strings.Contains(got, grant+"(../../embedding.md#the-module-grant)") {
		t.Errorf("modules/os.md:\n%s", got)
	}
	if got := string(pages[MatrixPage]); !strings.Contains(got, matrix+"(../types.md#member-functions-are-values)") {
		t.Errorf("%s:\n%s", MatrixPage, got)
	}
	// rendered, the guide checked: a missing heading is refused
	write("types.md", "# Types\n")
	if _, err := siteOf(t, &kavun).Pages(filepath.Join(docs, "reference")); err == nil ||
		!strings.Contains(err.Error(), `kavun:doc/types#member-functions-are-values: types.md has no heading or anchor "member-functions-are-values"`) {
		t.Errorf("a missing guide heading: %v", err)
	}

	// not rendered: under Kavun's docs URL
	pages, err = siteOf(t, ref).Pages("reference")
	if err != nil {
		t.Fatal(err)
	}
	if got := string(pages["modules/os.md"]); !strings.Contains(got, grant+"("+kavunDocs+"/embedding.md#the-module-grant)") {
		t.Errorf("modules/os.md:\n%s", got)
	}
	if got := string(pages[MatrixPage]); !strings.Contains(got, matrix+"("+kavunDocs+"/types.md#member-functions-are-values)") {
		t.Errorf("%s:\n%s", MatrixPage, got)
	}

	// neither: refused, once per link
	site, err := NewSite([]*reference.Reference{ref}, []*reference.Reference{ref}, nil)
	if err != nil {
		t.Fatal(err)
	}
	_, err = site.Pages("reference")
	for _, link := range []string{"kavun:doc/embedding#the-module-grant", "kavun:doc/types#member-functions-are-values"} {
		if err == nil || strings.Count(err.Error(), link+": a page of Kavun's guide, and Kavun's reference is neither rendered nor given a docs URL") != 1 {
			t.Errorf("%s: %v", link, err)
		}
	}
}

// TestRelPath: the path from one page to another, both below one root.
func TestRelPath(t *testing.T) {
	for _, c := range [][3]string{
		{"types/a.md", "types/b.md", "b.md"},
		{"types/a.md", "modules/fin.md", "../modules/fin.md"},
		{"builtins.md", "types/time.md", "types/time.md"},
		{"modules.md", "modules/os.md", "modules/os.md"},
		{"reference/types/a.md", "embedding.md", "../../embedding.md"},
		{"reference/builtins.md", "guides/x.md", "../guides/x.md"},
		{"a/b/c.md", "a/d.md", "../d.md"},
	} {
		if got := relPath(c[0], c[1]); got != c[2] {
			t.Errorf("relPath(%q, %q) = %q, want %q", c[0], c[1], got, c[2])
		}
	}
}
