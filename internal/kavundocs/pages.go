package kavundocs

import (
	"fmt"
	"slices"
	"strings"

	"github.com/jokruger/kavun/reference"
)

// The page renderer: the Markdown reference — one page per type, the builtins page, one page per module, the module
// index and the member-function matrix — from a set of references alone. A doc block is Markdown and passes through
// verbatim (reference.Doc.Markdown); everything else on a page (titles, headings, anchors, order, paths) is decided
// here.

// mdHeader opens every generated page; %s lists its source files (the reference positions' files).
const mdHeader = "<!-- Code generated by kavun-docs from %s; DO NOT EDIT. -->\n"

// page is one page while it is being assembled: its path below the output root, its blocks (joined by blank lines)
// and the source files they came from.
type page struct {
	path    string
	links   *linker
	blocks  []string
	sources map[string]bool
}

func (l *linker) newPage(path string) *page {
	return &page{path: path, links: l, sources: map[string]bool{}}
}

// text answers a summary or a doc body with its kavun: links rendered for this page; pos is the declaration's, for
// a link that cannot be rendered.
func (p *page) text(md string, pos reference.Pos) string {
	return p.links.render(p.path, md, pos)
}

// doc answers a doc body as Markdown (reference.Doc.Markdown), the kavun: links of its text blocks rendered for this
// page.
func (p *page) doc(d reference.Doc, pos reference.Pos) string {
	out := make(reference.Doc, len(d))
	for i, b := range d {
		if b.Kind == reference.BlockText {
			b.Markdown = p.text(b.Markdown, pos)
		}
		out[i] = b
	}
	return out.Markdown()
}

// kavunText answers text of kavun-docs' own with its kavun:doc/ links — pages of Kavun's guide, whoever's reference
// is rendered — rendered for this page (linker.kavunGuide).
func (p *page) kavunText(md string) string {
	return p.links.kavunText(p.path, md)
}

// block appends one block of text; empty text adds nothing.
func (p *page) block(text string) {
	if text != "" {
		p.blocks = append(p.blocks, text)
	}
}

// from records the source file of a declaration.
func (p *page) from(pos reference.Pos) {
	p.sources[pos.File] = true
}

// bytes renders the page: the generated-file header naming the sources in order, then the blocks.
func (p *page) bytes() []byte {
	sources := make([]string, 0, len(p.sources))
	for s := range p.sources {
		sources = append(sources, s)
	}
	slices.Sort(sources)
	return []byte(fmt.Sprintf(mdHeader, strings.Join(sources, ", ")) + strings.Join(p.blocks, "\n\n") + "\n")
}

// head adds a page's title and its root block (summary, then the body); lead, when not empty, goes between the
// summary and the body.
func (p *page) head(title, summary string, doc reference.Doc, pos reference.Pos, lead ...string) {
	p.from(pos)
	p.block("# " + title)
	p.block(p.text(summary, pos))
	for _, l := range lead {
		p.block(l)
	}
	p.block(p.doc(doc, pos))
}

// The grant line every module page carries, from the module's purity. Its link is to Kavun's guide (kavunText).
const (
	grantPure  = "**Pure** — importable by default."
	grantWorld = "**World access** — needs a grant (see [embedding.md § The module grant](kavun:doc/embedding#the-module-grant))."
)

// grantLine answers a module page's grant line.
func grantLine(pure bool) string {
	if pure {
		return grantPure
	}
	return grantWorld
}

// entries adds the page's entry list under heading ("Members", "Functions"): an index with one line per entry,
// linking to it, then one `###` entry each — both in alphabetical (byte) order of the name, so `x` sits beside
// `x_in_place`. Each entry gets an explicit anchor named after it (`#pad_start`): the heading text's own slug would
// change with the signature.
func (p *page) entries(heading string, cs []reference.Callable) {
	cs = slices.Clone(cs)
	slices.SortFunc(cs, func(a, b reference.Callable) int { return strings.Compare(a.Name, b.Name) })
	p.block("## " + heading)
	var index []string
	for _, c := range cs {
		index = append(index, "- ["+renderSignature(c)+"](#"+c.Name+")")
	}
	p.block(strings.Join(index, "\n"))
	for _, c := range cs {
		p.from(c.Pos)
		p.block(fmt.Sprintf("<a id=%q></a>\n### %s", c.Name, renderSignature(c)))
		p.block(p.text(c.Summary, c.Pos))
		p.block(p.doc(c.Doc, c.Pos))
	}
}

// constants adds a module's constants under ConstantsHeading, in the form of entries: an index linking to each, then
// one `###` entry each, alphabetical, anchored by name, headed by the name and the type (`pi -> float`).
func (p *page) constants(cs []reference.Constant) {
	cs = slices.Clone(cs)
	slices.SortFunc(cs, func(a, b reference.Constant) int { return strings.Compare(a.Name, b.Name) })
	p.block("## " + ConstantsHeading)
	var index []string
	for _, c := range cs {
		index = append(index, "- ["+renderConstant(c)+"](#"+c.Name+")")
	}
	p.block(strings.Join(index, "\n"))
	for _, c := range cs {
		p.from(c.Pos)
		p.block(fmt.Sprintf("<a id=%q></a>\n### %s", c.Name, renderConstant(c)))
		p.block(p.text(c.Summary, c.Pos))
		p.block(p.doc(c.Doc, c.Pos))
	}
}

// renderConstant renders a constant's heading: `pi -> float`.
func renderConstant(c reference.Constant) string {
	return "`" + c.Name + " -> " + c.Type + "`"
}

// renderSignature renders an entry's signature, every reading of its template with the result, joined by " / ":
//
//	`splice([start[, delete_count]]) -> array` / `splice(start, delete_count, ...items) -> array`
func renderSignature(c reference.Callable) string {
	var readings []string
	// a template joins its readings with exactly " | ", which no reading contains
	for _, reading := range strings.Split(c.Signature.Template, " | ") {
		readings = append(readings, "`"+c.Name+reading+" -> "+c.Result+"`")
	}
	return strings.Join(readings, " / ")
}

// The page titles that are not a type's or a module's name.
const (
	builtinsTitle = "Builtin functions"
	modulesTitle  = "Modules"
)

// The `##` headings of the entry lists: a type's members, the functions of the builtins or a module, a module's
// constants. A root block cannot use them for a section of its own where the page has that list (cmd/kavun-gen
// refuses it).
const (
	MembersHeading   = "Members"
	FunctionsHeading = "Functions"
	ConstantsHeading = "Constants"
)

// The paths of the pages that are not a type's or a module's, below the output root.
const (
	BuiltinsPage = "builtins.md"
	ModulesPage  = "modules.md"
	MatrixPage   = "function_matrix.md"
)

// TypePage is the page of a type below the output root: types/<name>.md, with the dot of a module-owned type's name
// (fs.file) as an underscore (types/fs_file.md).
func TypePage(name string) string {
	return "types/" + strings.ReplaceAll(name, ".", "_") + ".md"
}

// ModulePage is the page of a module below the output root: modules/<name>.md.
func ModulePage(name string) string {
	return "modules/" + name + ".md"
}

// Pages renders the Markdown reference of every rendered reference of the site, keyed by slash-separated path below
// the output root: TypePage for each type, BuiltinsPage, ModulePage for each module, the module index ModulesPage
// (when there is a module) and the member-function matrix MatrixPage (when some type has members). A page two
// declarations would both produce (two builtins blocks, two types whose names map to one file) is refused, and so
// is a kavun: link that cannot be rendered (links.go). outRoot is the output root (<docs root>/reference): a
// kavun:doc/ link names a file of its parent, the docs root.
func (s *Site) Pages(outRoot string) (map[string][]byte, error) {
	set := s.Rendered
	links := s.linker(outRoot)
	out := map[string][]byte{}
	owner := map[string]string{} // page path → what claimed it
	var problems []string
	claim := func(rel, what string) bool {
		if prev, ok := owner[rel]; ok {
			problems = append(problems, fmt.Sprintf("%s would be generated twice: by %s and by %s", rel, prev, what))
			return false
		}
		owner[rel] = what
		return true
	}

	var modules []*reference.Module
	for _, ref := range set.References() {
		for i := range ref.Types {
			t := &ref.Types[i]
			rel := TypePage(t.Name)
			if !claim(rel, fmt.Sprintf("type %s (%s, %s)", t.Name, ref.Origin, t.Pos)) {
				continue
			}
			p := links.newPage(rel)
			p.head(t.Name, t.Summary, t.Doc, t.Pos)
			if len(t.Members) > 0 {
				p.entries(MembersHeading, t.Members)
			}
			out[rel] = p.bytes()
		}
		if b := ref.Builtins; b != nil && claim(BuiltinsPage, fmt.Sprintf("the builtins of %s (%s)", ref.Origin, b.Pos)) {
			p := links.newPage(BuiltinsPage)
			p.head(builtinsTitle, "", b.Doc, b.Pos)
			p.entries(FunctionsHeading, b.Functions)
			out[BuiltinsPage] = p.bytes()
		}
		for i := range ref.Modules {
			m := &ref.Modules[i]
			rel := ModulePage(m.Name)
			if !claim(rel, fmt.Sprintf("module %s (%s, %s)", m.Name, ref.Origin, m.Pos)) {
				continue
			}
			p := links.newPage(rel)
			p.head(m.Name, m.Summary, m.Doc, m.Pos, p.kavunText(grantLine(m.Pure)))
			p.entries(FunctionsHeading, m.Functions)
			if len(m.Constants) > 0 {
				p.constants(m.Constants)
			}
			out[rel] = p.bytes()
			modules = append(modules, m)
		}
	}
	if len(modules) > 0 {
		out[ModulesPage] = renderModuleIndex(links.newPage(ModulesPage), modules)
	}
	if matrix := renderFunctionMatrix(links.newPage(MatrixPage), set); matrix != nil {
		out[MatrixPage] = matrix
	}
	problems = append(problems, links.problems...)
	if len(problems) > 0 {
		return nil, fmt.Errorf("rendering the reference: %s", strings.Join(problems, "; "))
	}
	return out, nil
}

// renderModuleIndex renders the module index: one row per module, in name order, with its grant spelled out and its
// summary.
func renderModuleIndex(p *page, modules []*reference.Module) []byte {
	modules = slices.Clone(modules)
	slices.SortFunc(modules, func(a, b *reference.Module) int { return strings.Compare(a.Name, b.Name) })
	p.block("# " + modulesTitle)
	rows := []string{"| module | grant | summary |", "| --- | --- | --- |"}
	for _, m := range modules {
		p.from(m.Pos)
		grant := "needs a grant"
		if m.Pure {
			grant = "importable by default"
		}
		rows = append(rows, fmt.Sprintf("| [%s](%s) | %s | %s |", m.Name, relPath(p.path, ModulePage(m.Name)), grant, strings.ReplaceAll(p.text(m.Summary, m.Pos), "|", `\|`)))
	}
	p.block(strings.Join(rows, "\n"))
	return p.bytes()
}

// renderFunctionMatrix renders the member-function matrix: which member each type answers. Columns are the types
// with members — builtin types, then module-owned types (reference.Type.Module), each in name order; rows are every
// member name a column declares. nil when no type has members.
func renderFunctionMatrix(p *page, set *reference.Set) []byte {
	type column struct {
		name    string
		members map[string]bool
	}
	var builtin, owned []column
	for _, ref := range set.References() {
		for _, t := range ref.Types {
			if len(t.Members) == 0 {
				continue
			}
			p.from(t.Pos)
			c := column{name: t.Name, members: map[string]bool{}}
			for _, m := range t.Members {
				c.members[m.Name] = true
			}
			if t.Module != "" {
				owned = append(owned, c)
			} else {
				builtin = append(builtin, c)
			}
		}
	}
	if len(builtin)+len(owned) == 0 {
		return nil
	}
	table := func(cols []column) string {
		slices.SortFunc(cols, func(a, b column) int { return strings.Compare(a.name, b.name) })
		rows := map[string]bool{}
		head := []string{"member"}
		rule := []string{"---"}
		for _, c := range cols {
			for n := range c.members {
				rows[n] = true
			}
			head = append(head, "["+c.name+"]("+relPath(p.path, TypePage(c.name))+")")
			rule = append(rule, "---")
		}
		names := make([]string, 0, len(rows))
		for n := range rows {
			names = append(names, n)
		}
		slices.Sort(names)
		lines := []string{"| " + strings.Join(head, " | ") + " |", "| " + strings.Join(rule, " | ") + " |"}
		for _, n := range names {
			cells := []string{"`" + n + "`"}
			for _, c := range cols {
				if c.members[n] {
					cells = append(cells, "✓")
				} else {
					cells = append(cells, "—")
				}
			}
			lines = append(lines, "| "+strings.Join(cells, " | ")+" |")
		}
		return strings.Join(lines, "\n")
	}
	p.block("# " + matrixTitle)
	p.block(p.kavunText(matrixIntro))
	if len(builtin) > 0 {
		p.block("## Builtin types")
		p.block(table(builtin))
	}
	if len(owned) > 0 {
		p.block("## Module-owned types")
		p.block(table(owned))
	}
	return p.bytes()
}

const (
	matrixTitle = "Member-function matrix"
	matrixIntro = "Which member functions each type answers. The page is generated from the same `//kavun:member`\n" +
		"directives the types' `Methods` tables are generated from, so it cannot disagree with them.\n" +
		"It answers existence only — each type's page carries the contracts.\n\n" +
		"`✓` = the type answers the member; `—` = no member-call form on that type (a free builtin or an operator of\n" +
		"the same meaning may still exist). `record` has no member surface by design (free builtins only), the callable\n" +
		"kinds have only the universal members, and a `module`'s members are built per module at run time, so none of\n" +
		"them is a column.\n\n" +
		"Every `✓` member is also readable as a value: `x.name` without a call answers a bound member of `x`\n" +
		"([member functions are values](kavun:doc/types#member-functions-are-values))."
)
