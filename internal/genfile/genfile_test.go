func TestUnifiedDiff(t *testing.T) {
	got := UnifiedDiff("a", "b", "1\n2\n3\n", "1\n3\n4\n")
	want := "--- a\n+++ b\n@@ -1,3 +1,3 @@\n 1\n-2\n 3\n+4\n"
	if got != want {
		t.Fatalf("got\n%s\nwant\n%s", got, want)
	}

	// any pair: applying the hunks to a gives b (the common head and tail are kept out of the table)
	words := []string{"a", "b", "c"}
	for seed := range 3000 {
		r := rand.New(rand.NewPCG(uint64(seed), 1))
		gen := func() string {
			var sb strings.Builder
			for range r.IntN(12) {
				sb.WriteString(words[r.IntN(len(words))] + "\n")
			}
			return sb.String()
		}
		a, b := gen(), gen()
		if got := applyDiff(t, a, UnifiedDiff("a", "b", a, b)); got != b {
			t.Fatalf("seed %d: %q → %q gives %q", seed, a, b, got)
		}
	}
}

// applyDiff applies a unifiedDiff to a, checking every context and removed line against it.
func applyDiff(t *testing.T, a, diff string) string {
	t.Helper()
	x := splitLines(a)
	var out []string
	next := 0 // the first line of a not yet copied
	for _, line := range splitLines(diff)[2:] {
		if strings.HasPrefix(line, "@@") {
			var start, n int
			if _, err := fmt.Sscanf(line, "@@ -%d,%d", &start, &n); err != nil {
				t.Fatalf("bad hunk header %q", line)
			}
			if n > 0 || start > 0 {
				start-- // a header names lines from 1
			}
			out = append(out, x[next:start]...)
			next = start
			continue
		}
		switch line[0] {
		case ' ', '-':
			if x[next] != line[1:] {
				t.Fatalf("line %d is %q, the diff says %q", next+1, x[next], line[1:])
			}
			if line[0] == ' ' {
				out = append(out, x[next])
			}
			next++
		case '+':
			out = append(out, line[1:])
		}
	}
	out = append(out, x[next:]...)
	if len(out) == 0 {
		return ""
	}
	return strings.Join(out, "\n") + "\n"
}

// hdr is a generated header; the tool name is any word.
const hdr = "<!-- Code generated by some-tool from x.go; DO NOT EDIT. -->\n"

// TestTree: a wholly generated directory — every content in path order, then a deletion for every file nothing
// produces; Check reports the differences, Write applies them, and Check is clean afterwards.
func TestTree(t *testing.T) {
	dir := filepath.Join(t.TempDir(), "out")
	contents := map[string][]byte{"b.md": []byte(hdr + "b\n"), "sub/a.md": []byte(hdr + "a\n")}
	files, err := Tree(dir, contents)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 2 || files[0].Path != filepath.Join(dir, "b.md") || files[1].Path != filepath.Join(dir, "sub", "a.md") {
		t.Fatalf("a missing directory: %v", files)
	}
	if diffs, _ := Check(files); len(diffs) != 2 || !strings.Contains(diffs[0], "+b") {
		t.Fatalf("Check before Write should report both files, got %v", diffs)
	}
	if err := Write(files); err != nil {
		t.Fatal(err)
	}
	if diffs, _ := Check(files); len(diffs) != 0 {
		t.Fatalf("Check after Write should be clean, got %v", diffs)
	}

	// a generated page nothing produces any more, written by another tool name, and an edited generated page
	stale := filepath.Join(dir, "sub", "gone.md")
	if err := os.WriteFile(stale, []byte("<!-- Code generated by kavun-gen from y.go; DO NOT EDIT. -->\nold\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(filepath.Join(dir, "b.md"), []byte(hdr+"edited\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	files, err = Tree(dir, contents)
	if err != nil {
		t.Fatal(err)
	}
	if len(files) != 3 || files[2].Path != stale || files[2].Content != nil {
		t.Fatalf("expected the stale file last, got %v", files)
	}
	diffs, _ := Check(files)
	if len(diffs) != 2 || !strings.Contains(diffs[0], "-edited") || !strings.Contains(diffs[1], "gone.md (on disk)") || !strings.Contains(diffs[1], "-old") {
		t.Fatalf("Check should diff the edited and the stale file, got %v", diffs)
	}
	if err := Write(files); err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("the stale file still exists")
	}
	if diffs, _ := Check(files); len(diffs) != 0 {
		t.Fatalf("Check after Write should be clean, got %v", diffs)
	}
}

// TestTreeRefusesForeignFiles: a file under the directory without a generated header — a hand-written page (stale
// or about to be overwritten), an image — is refused, each named, and Tree answers no file to write or delete.
func TestTreeRefusesForeignFiles(t *testing.T) {
	dir := t.TempDir()
	foreign := map[string]string{
		"guide.md":  "# A guide\n\nWritten by hand.\n",
		"pic.png":   "\x89PNG\r\n\x1a\n",
		"b.md":      "b, by hand: would be overwritten\n",
		"empty.md":  "",
		"almost.md": "<!-- Code generated by x; DO NOT EDIT -->\n", // no period
		"second.md": "intro\n" + hdr,                               // the header must be the first line
	}
	for name, content := range foreign {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "gen.md"), []byte(hdr+"stale\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	files, err := Tree(dir, map[string][]byte{"b.md": []byte(hdr + "b\n")})
	if err == nil || files != nil {
		t.Fatalf("expected a refusal, got %v, %v", files, err)
	}
	for name := range foreign {
		if !strings.Contains(err.Error(), filepath.ToSlash(filepath.Join(dir, name))) {
			t.Errorf("the refusal does not name %s: %v", name, err)
		}
	}
	if strings.Contains(err.Error(), "gen.md") {
		t.Errorf("the refusal names a generated file: %v", err)
	}

	for _, c := range []struct {
		line string
		want bool
	}{
		{"<!-- Code generated by kavun-gen from core/array.go, core/array_members.go; DO NOT EDIT. -->\nbody", true},
		{"<!-- Code generated by kavun-docs from x.go; DO NOT EDIT. -->\r\n", true},
		{"<!-- Code generated by kavun-docs; DO NOT EDIT. -->", true},
		{"<!-- Code generated by; DO NOT EDIT. -->", false}, // no tool name
		{"// Code generated by kavun-gen; DO NOT EDIT.", false},
		{"", false},
	} {
		if got := IsGenerated([]byte(c.line)); got != c.want {
			t.Errorf("IsGenerated(%q) = %v", c.line, got)
		}
	}
}
