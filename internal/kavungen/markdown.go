// The Markdown emitter: the second output of the same parse. It writes the reference pages under docs/reference/ —
// one page per type, the builtins page, one page per module and the module index — from the doc blocks of the
// directives. A doc block's body is Markdown and passes through verbatim; the only rewrite undoes what gofmt does to
// a fenced block written in its code-block form (see renderBody), so that gofmt on a source file never changes the
// generated Markdown.

// mdHeader opens every generated Markdown file; %s lists its source files.
const mdHeader = "<!-- Code generated by kavun-gen from %s; DO NOT EDIT. -->\n"

// fenceSpan is one fenced block of a doc body: the indexes of its opening and closing fence lines (close is -1 when
// the body ends first).
type fenceSpan struct {
	open, close int
}

// fenceSpans answers the fenced blocks of a body. Only backtick fences are recognised, unindented: a line of three
// or more backticks opens one (an info string may follow), and, as in CommonMark, only a line of at least as many
// backticks and nothing else closes it — a shorter run inside is content. checkMarkdown and renderBody both read
// the body through it, so what is checked is what is rendered.
func fenceSpans(lines []string) []fenceSpan {
	var spans []fenceSpan
	for i := 0; i < len(lines); i++ {
		n := backtickRun(lines[i])
		if n < 3 {
			continue
		}
		span := fenceSpan{open: i, close: -1}
		for j := i + 1; j < len(lines); j++ {
			if m := backtickRun(lines[j]); m >= n && strings.TrimSpace(lines[j][m:]) == "" {
				span.close = j
				break
			}
		}
		spans = append(spans, span)
		if span.close < 0 {
			break
		}
		i = span.close
	}
	return spans
}

// backtickRun answers the number of backticks a line starts with.
func backtickRun(line string) int {
	return len(line) - len(strings.TrimLeft(line, "`"))
}

// topHeading matches a `#` or `##` Markdown heading line.
var topHeading = regexp.MustCompile(`^##?( |$)`)

// checkMarkdown applies the rules that keep a doc block's Markdown well-formed on the page and stable under gofmt,
// which reformats the doc comment of a declaration: no line indented outside a fenced block (gofmt would make it a
// Go code block, Markdown a code block), fenced blocks with backticks only, closed, and indented in a way gofmt
// keeps (checkFence). A `#` or `##` heading is the page's own structure: it is allowed only in a page root's block
// (allowTop), never in an entry's body. Each problem is reported at its line; ok is false when there was
// any.
func checkMarkdown(lines []string, pos []token.Position, allowTop bool, errs *errorList) bool {
	ok := true
	fenced := make([]bool, len(lines)) // the fence lines and the content of every fenced block
	for _, sp := range fenceSpans(lines) {
		end := sp.close
		if end < 0 {
			errs.add(pos[sp.open], "unclosed fenced block: the doc block ends before a closing line of at least %d backticks", backtickRun(lines[sp.open]))
			ok = false
			end = len(lines) - 1
		} else {
			ok = checkFence(lines[sp.open+1:sp.close], pos[sp.open+1:sp.close], errs) && ok
		}
		if lang, noRun, _ := fenceInfo(lines[sp.open]); lang == "go" && !noRun && strings.TrimSpace(strings.TrimLeft(lines[sp.open], "`")) != "go" {
			errs.add(pos[sp.open], "a `go` fence takes nothing after the language but the `%s` marker of an example that is not run (```go %s [reason])", NoRun, NoRun)
			ok = false
		}
		for i := sp.open; i <= end; i++ {
			fenced[i] = true
		}
	}
	for i, line := range lines {
		switch {
		case fenced[i]:
		case strings.HasPrefix(line, "~~~"):
			errs.add(pos[i], "a `~~~` fence: only backtick fences are recognised (write ``` instead)")
			ok = false
		case isIndented(line):
			errs.add(pos[i], "doc line is indented outside a fenced block: gofmt and Markdown would both read it as a code block (lists are single-level, their continuation lines unindented)")
			ok = false
		case !allowTop && topHeading.MatchString(line):
			errs.add(pos[i], "a `#` or `##` heading belongs to the page's structure (the type, module or builtins block): an entry's body uses `####` and deeper")
			ok = false
		}
	}
	return ok
}

// checkFence checks the content lines of one fenced block. Either no line is indented, or the block is in gofmt's
// code-block form: every non-blank line starts with one tab, and at least one has nothing else before its text
// (gofmt strips indentation common to every line, so a block indented further throughout would lose it).
func checkFence(lines []string, pos []token.Position, errs *errorList) bool {
	firstTab, firstPlain, flush := -1, -1, false
	for i, line := range lines {
		switch {
		case isBlank(line):
		case line[0] == ' ':
			errs.add(pos[i], "doc line inside a fenced block is indented with spaces: gofmt would turn it into a Go code block; put a tab before every line of the block instead (`//<tab>…`, gofmt's code-block form)")
			return false
		case line[0] == '\t':
			if firstTab < 0 {
				firstTab = i
			}
			flush = flush || !isIndented(line[1:])
		default:
			if firstPlain < 0 {
				firstPlain = i
			}
		}
	}
	switch {
	case firstTab >= 0 && firstPlain >= 0:
		errs.add(pos[max(firstTab, firstPlain)], "a fenced block mixes tab-indented and unindented lines: gofmt would split it; put a tab before every line of the block, or before none")
		return false
	case firstTab >= 0 && !flush:
		errs.add(pos[firstTab], "every line of a tab-indented fenced block is indented past its tab: gofmt would strip the common indentation; let the least indented line start right after the tab")
		return false
	}
	return true
}

func isIndented(line string) bool {
	return line != "" && (line[0] == ' ' || line[0] == '\t') && !isBlank(line)
}

func isBlank(line string) bool {
	return strings.TrimSpace(line) == ""
}

// renderBody answers a doc body as Markdown lines: verbatim, except that a fenced block in gofmt's code-block form
// (its lines after a tab) loses that tab and the blank lines gofmt puts between a code block and the fence lines
// around it, and that an example's `norun` marker (examples.go) is dropped from its fence (pageFence).
func renderBody(body []string) []string {
	var out []string
	next := 0 // the first line not yet copied
	for _, sp := range fenceSpans(body) {
		if sp.close < 0 { // refused by checkMarkdown; copied as it is
			break
		}
		out = append(out, body[next:sp.open]...)
		out = append(out, pageFence(body[sp.open]))
		content := body[sp.open+1 : sp.close]
		if slices.ContainsFunc(content, func(l string) bool { return strings.HasPrefix(l, "\t") }) {
			for _, l := range trimBlank(content) {
				out = append(out, strings.TrimPrefix(l, "\t"))
			}
		} else {
			out = append(out, content...)
		}
		out = append(out, body[sp.close])
		next = sp.close + 1
	}
	return append(out, body[next:]...)
}

// pageFence answers a fence line as the page shows it: a ```go norun [reason] fence, an example that is not run,
// is shown as a plain ```go fence — the marker is for TestDocExamples, not for the reader.
func pageFence(line string) string {
	if lang, noRun, _ := fenceInfo(line); lang == "go" && noRun {
		return line[:backtickRun(line)] + "go"
	}
	return line
}

// mdPage is one generated Markdown page while it is being assembled: its blocks (joined by blank lines) and the
// source files they came from.
type mdPage struct {
	blocks  []string
	sources map[string]bool
}

func newMDPage() *mdPage {
	return &mdPage{sources: map[string]bool{}}
}

// block appends one block of text; empty text adds nothing.
func (p *mdPage) block(text string) {
	if text != "" {
		p.blocks = append(p.blocks, text)
	}
}

// from records the source file of a directive, relative to the module root.
func (p *mdPage) from(m *packageModel, d Directive) {
	p.sources[path.Join(m.relDir, filepath.Base(d.Pos.Filename))] = true
}

// bytes renders the page: the generated-file header naming the sources in order, then the blocks.
func (p *mdPage) bytes() []byte {
	sources := make([]string, 0, len(p.sources))
	for s := range p.sources {
		sources = append(sources, s)
	}
	slices.Sort(sources)
	return []byte(fmt.Sprintf(mdHeader, strings.Join(sources, ", ")) + strings.Join(p.blocks, "\n\n") + "\n")
}

// head adds a page's title and its root directive's doc block (summary, then intro); lead, when not empty, goes
// between the summary and the intro.
func (p *mdPage) head(m *packageModel, title string, root Directive, lead ...string) {
	p.from(m, root)
	p.block("# " + title)
	p.block(root.Doc.Summary)
	for _, l := range lead {
		p.block(l)
	}
	p.block(strings.Join(renderBody(root.Doc.Body), "\n"))
}

// The grant line every module page carries, derived from the //kavun:module directive's purity.
const (
	grantPure  = "**Pure** — importable by default."
	grantWorld = "**World access** — needs a grant (see [embedding.md § The module grant](../../embedding.md#the-module-grant))."
)

// grantLine answers a module page's grant line.
func grantLine(pure bool) string {
	if pure {
		return grantPure
	}
	return grantWorld
}

// entries adds the page's entry list under heading ("Members", "Functions"): an index with one line per entry, linking
// to it, then one `###` entry each — both in alphabetical (byte) order of the name, so source order carries no
// meaning and `x` sits beside `x_in_place`. Each entry gets an explicit anchor named after it (`#pad_start`):
// the heading text's own slug would change with the signature.
func (p *mdPage) entries(m *packageModel, heading string, ds []Directive) {
	ds = slices.Clone(ds)
	slices.SortFunc(ds, func(a, b Directive) int { return strings.Compare(a.Name, b.Name) })
	p.block("## " + heading)
	var index []string
	for _, d := range ds {
		index = append(index, "- ["+renderSignature(d)+"](#"+d.Name+")")
	}
	p.block(strings.Join(index, "\n"))
	for _, d := range ds {
		p.from(m, d)
		p.block(fmt.Sprintf("<a id=%q></a>\n### %s", d.Name, renderSignature(d)))
		p.block(d.Doc.Summary)
		p.block(strings.Join(renderBody(d.Doc.Body), "\n"))
	}
}

// renderSignature renders an entry's signature, every reading with the result, joined by " / ":
//
//	`splice([start[, delete_count]]) -> array` / `splice(start, delete_count, ...items) -> array`
func renderSignature(d Directive) string {
	var readings []string
	// a parsed template joins its readings with exactly " | ", which no reading contains
	for _, reading := range strings.Split(d.Template, " | ") {
		readings = append(readings, "`"+d.Name+reading+" -> "+d.Result+"`")
	}
	return strings.Join(readings, " / ")
}

// The page titles that are not a type's or a module's name, and the headings of the entry lists.
const (
	builtinsTitle    = "Builtin functions"
	stdlibTitle      = "Standard library"
	membersHeading   = "Members"
	functionsHeading = "Functions"
)

// moduleRow is what the stdlib.md index shows of one module.
type moduleRow struct {
	name    string
	pure    bool
	summary string
	source  string // the file of its //kavun:module, relative to the module root
}

// renderStdlibIndex renders stdlib.md: one row per module, in name order, with its grant spelled out and its
// summary.
func renderStdlibIndex(modules []moduleRow) []byte {
	modules = slices.Clone(modules)
	slices.SortFunc(modules, func(a, b moduleRow) int { return strings.Compare(a.name, b.name) })
	p := newMDPage()
	p.block("# " + stdlibTitle)
	rows := []string{"| module | grant | summary |", "| --- | --- | --- |"}
	for _, r := range modules {
		p.sources[r.source] = true
		grant := "needs a grant"
		if r.pure {
			grant = "importable by default"
		}
		rows = append(rows, fmt.Sprintf("| [%s](stdlib/%s.md) | %s | %s |", r.name, r.name, grant, strings.ReplaceAll(r.summary, "|", `\|`)))
	}
	p.block(strings.Join(rows, "\n"))
	return p.bytes()
}

// emitDocs renders the Markdown pages of the given packages, keyed by their slash-separated path below the docs
// root: types/<type>.md, builtins.md, stdlib/<module>.md and the stdlib.md index. A page that two packages would
// both write is refused.
func emitDocs(models []*packageModel) (map[string][]byte, errorList) {
	var errs errorList
	out := map[string][]byte{}
	owner := map[string]Directive{} // page path → the root directive that claimed it
	claim := func(rel string, root Directive) bool {
		if prev, ok := owner[rel]; ok {
			errs.add(root.Pos, "%s would be generated twice (first from %s)", rel, where(prev.Pos))
			return false
		}
		owner[rel] = root
		return true
	}

	var modules []moduleRow

	for _, m := range models {
		for _, t := range m.types {
			rel := typePage(t.decl.Name)
			if !claim(rel, t.decl) {
				continue
			}
			p := newMDPage()
			p.head(m, t.decl.Name, t.decl)
			if t.hasMembers {
				p.entries(m, membersHeading, t.members)
			}
			out[rel] = p.bytes()
		}
		if m.builtins != nil && claim("builtins.md", *m.builtins) {
			p := newMDPage()
			p.head(m, builtinsTitle, *m.builtins)
			p.entries(m, functionsHeading, m.builtinFuncs)
			out["builtins.md"] = p.bytes()
		}
		if m.module != nil {
			rel := "stdlib/" + m.module.Name + ".md"
			if !claim(rel, *m.module) {
				continue
			}
			p := newMDPage()
			p.head(m, m.module.Name, *m.module, grantLine(m.module.Pure))
			p.entries(m, functionsHeading, m.moduleFuncs)
			out[rel] = p.bytes()
			modules = append(modules, moduleRow{m.module.Name, m.module.Pure, m.module.Doc.Summary, path.Join(m.relDir, filepath.Base(m.module.Pos.Filename))})
		}
	}

	if len(modules) > 0 {
		out["stdlib.md"] = renderStdlibIndex(modules)
	}
	return out, errs
}

// typePage is the page file of a type under the docs root: types/<name>.md, with the dot of a module-owned type's name
// (fs.file) as an underscore (types/fs_file.md).
func typePage(name string) string {
	return "types/" + strings.ReplaceAll(name, ".", "_") + ".md"
}

// matrixPage is the generated member-function matrix, under the docs root.
const matrixPage = "function_matrix.md"

// renderFunctionMatrix renders function_matrix.md: which member each type answers, from the same directives the
// types' Methods tables come from, so the matrix cannot disagree with them. Columns are the types with a members
// table — builtin types, then module-owned types, each in name order; rows are every member name a column declares.
// It is written only by a run over the whole module (a partial run sees only some of the columns), and only when
// some type has a members table (nil otherwise).
func renderFunctionMatrix(models []*packageModel) []byte {
	type column struct {
		name    string
		members map[string]bool
	}
	var builtin, owned []column
	p := newMDPage()
	for _, m := range models {
		for _, t := range m.types {
			if !t.hasMembers {
				continue
			}
			p.from(m, t.decl)
			c := column{name: t.decl.Name, members: map[string]bool{}}
			for _, d := range t.members {
				c.members[d.Name] = true
			}
			if strings.Contains(t.decl.Name, ".") {
				owned = append(owned, c)
			} else {
				builtin = append(builtin, c)
			}
		}
	}
	if len(builtin)+len(owned) == 0 {
		return nil
	}
	table := func(cols []column) string {
		slices.SortFunc(cols, func(a, b column) int { return strings.Compare(a.name, b.name) })
		rows := map[string]bool{}
		head := []string{"member"}
		rule := []string{"---"}
		for _, c := range cols {
			for n := range c.members {
				rows[n] = true
			}
			head = append(head, "["+c.name+"]("+typePage(c.name)+")")
			rule = append(rule, "---")
		}
		names := make([]string, 0, len(rows))
		for n := range rows {
			names = append(names, n)
		}
		slices.Sort(names)
		lines := []string{"| " + strings.Join(head, " | ") + " |", "| " + strings.Join(rule, " | ") + " |"}
		for _, n := range names {
			cells := []string{"`" + n + "`"}
			for _, c := range cols {
				if c.members[n] {
					cells = append(cells, "✓")
				} else {
					cells = append(cells, "—")
				}
			}
			lines = append(lines, "| "+strings.Join(cells, " | ")+" |")
		}
		return strings.Join(lines, "\n")
	}
	p.block("# " + matrixTitle)
	p.block(matrixIntro)
	if len(builtin) > 0 {
		p.block("## Builtin types")
		p.block(table(builtin))
	}
	if len(owned) > 0 {
		p.block("## Module-owned types")
		p.block(table(owned))
	}
	return p.bytes()
}

const (
	matrixTitle = "Member-function matrix"
	matrixIntro = "Which member functions each type answers. The page is generated from the same `//kavun:member`\n" +
		"directives the types' `Methods` tables are generated from, so it cannot disagree with them.\n" +
		"It answers existence only — each type's page carries the contracts.\n\n" +
		"`✓` = the type answers the member; `—` = no member-call form on that type (a free builtin or an operator of\n" +
		"the same meaning may still exist). `record` has no member surface by design (free builtins only), the callable\n" +
		"kinds have only the universal members, and a `module`'s members are built per module at run time, so none of\n" +
		"them is a column.\n\n" +
		"Every `✓` member is also readable as a value: `x.name` without a call answers a bound member of `x`\n" +
		"([member functions are values](../types.md#member-functions-are-values))."
)
